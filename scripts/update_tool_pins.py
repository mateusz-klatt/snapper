"""Sync Dockerfile tool pins to the versions implied by the workspace state.

Updates the Dockerfile ARG pins for:

- ``COREPACK_VERSION`` from the latest npm-published corepack version.
- ``POETRY_VERSION`` from the Poetry version recorded in poetry.lock.

The script is intended to run after dependency refresh so Docker build tooling
stays aligned with the local workspace and the frontend/backend update flow.
"""

import argparse
import re
import subprocess
from pathlib import Path
from typing import Final

DOCKERFILE_NAME: Final = "Dockerfile"
LOCKFILE_NAME: Final = "poetry.lock"
COREPACK_PACKAGE: Final = "corepack"
COREPACK_ARG: Final = "COREPACK_VERSION"
POETRY_ARG: Final = "POETRY_VERSION"
POETRY_LOCK_HEADER_RE: Final[re.Pattern[str]] = re.compile(
    r"^# This file is automatically @generated by Poetry (?P<version>\d+\.\d+\.\d+) and should not be changed by hand\.$"
)


def _default_root() -> Path:
    """Return the repository root based on this script's location."""
    return Path(__file__).resolve().parent.parent


def read_poetry_lock_version(lock_path: Path) -> str:
    """Extract the Poetry generator version from poetry.lock.

    Args:
        lock_path: Path to the Poetry lock file.

    Returns:
        The Poetry version recorded in the lockfile header.
    """
    lines = lock_path.read_text(encoding="utf-8").splitlines()
    if not lines:
        raise ValueError(f"{lock_path} is empty")
    match = POETRY_LOCK_HEADER_RE.match(lines[0])
    if match is None:
        raise ValueError(f"Could not parse Poetry version from {lock_path}")
    return match.group("version")


def latest_npm_version(package_name: str) -> str:
    """Return the latest published npm version for the given package.

    Args:
        package_name: Package name to query with ``npm view``.

    Returns:
        Latest published package version.
    """
    result = subprocess.run(
        ["npm", "view", package_name, "version"],
        check=True,
        capture_output=True,
        text=True,
    )
    latest = result.stdout.strip()
    if not latest:
        raise ValueError(f"npm returned an empty version for {package_name}")
    return latest


def replace_arg_value(dockerfile_text: str, arg_name: str, version: str) -> str:
    """Replace a Dockerfile ARG assignment with an exact version string.

    Args:
        dockerfile_text: Full Dockerfile contents.
        arg_name: Dockerfile ``ARG`` name to update.
        version: Version value to assign.

    Returns:
        Updated Dockerfile contents.
    """
    pattern = re.compile(rf"^(ARG {re.escape(arg_name)}=).+$", re.MULTILINE)
    updated_text, replacements = pattern.subn(rf"\g<1>{version}", dockerfile_text)
    if replacements != 1:
        raise ValueError(f"Expected exactly one ARG {arg_name} assignment in Dockerfile")
    return updated_text


def sync_dockerfile_tool_pins(
    dockerfile_path: Path,
    *,
    corepack_version: str,
    poetry_version: str,
) -> bool:
    """Update Dockerfile ARG pins and return whether the file changed.

    Args:
        dockerfile_path: Path to the Dockerfile to update.
        corepack_version: Corepack version to write.
        poetry_version: Poetry version to write.

    Returns:
        ``True`` when the file changed, otherwise ``False``.
    """
    original = dockerfile_path.read_text(encoding="utf-8")
    updated = replace_arg_value(original, COREPACK_ARG, corepack_version)
    updated = replace_arg_value(updated, POETRY_ARG, poetry_version)
    if updated == original:
        return False
    dockerfile_path.write_text(updated, encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    """CLI entry point for syncing Dockerfile tool pins.

    Args:
        argv: Optional command-line argument override for tests.

    Returns:
        Process exit code.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=None, help="Repository root path")
    parser.add_argument("--corepack-version", default=None, help="Override corepack pin")
    parser.add_argument("--poetry-version", default=None, help="Override poetry pin")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve() if args.root is not None else _default_root()
    poetry_version = args.poetry_version or read_poetry_lock_version(root / LOCKFILE_NAME)
    corepack_version = args.corepack_version or latest_npm_version(COREPACK_PACKAGE)
    changed = sync_dockerfile_tool_pins(
        root / DOCKERFILE_NAME,
        corepack_version=corepack_version,
        poetry_version=poetry_version,
    )
    if changed:
        print(
            f"Updated {DOCKERFILE_NAME}: {COREPACK_ARG}={corepack_version}, {POETRY_ARG}={poetry_version}"
        )
    else:
        print(
            f"{DOCKERFILE_NAME} already matches {COREPACK_ARG}={corepack_version}, {POETRY_ARG}={poetry_version}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
