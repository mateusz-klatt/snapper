def _serialize_signal_envelope_canonical(envelope: JsonObject) -> bytes:
    """Canonical JSON bytes for hashing + size enforcement.

    ``allow_nan=False`` rejects ``NaN`` / ``Infinity`` at this point: those
    values are not valid JSON and round-trip differently between SQLite's
    ``JSON`` text storage and PostgreSQL ``JSONB``, so a downstream
    consumer reconstructing the envelope from the column would see a
    different hash than the one stored on the audit-event payload.
    ``sort_keys=True`` + tight separators give a stable canonical form so
    two equivalent envelopes hash identically regardless of build order.
    """
    return json.dumps(
        envelope,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")


def _signal_envelope_hash(envelope: JsonObject) -> str:
    """Canonical SHA-256 hex digest of the signal envelope.

    Stored in the ``ai_reviews.signal_snapshot_hash`` column AND on the
    ``ai_review_events.created`` payload so a consumer reconstructing the
    audit trail can confirm the envelope it sees matches the one the
    review was created from.
    """
    return hashlib.sha256(_serialize_signal_envelope_canonical(envelope)).hexdigest()


class AiReviewService:
    """Singleton owner of the ``ai_reviews`` state machine + future registry."""

    _instance: AiReviewService | None = None
    _initialized: bool = False

    def __new__(cls) -> AiReviewService:
        """Create or return the singleton instance."""
        if cls._instance is None:
            instance = super().__new__(cls)
            cls._instance = instance
        return cls._instance

    def __init__(self) -> None:
        """Initialise publisher slot + futures registry on first construction."""
        if self._initialized:
            return
        self._initialized = True
        self._msg_publisher: MessagePublisher | None = None
        self._futures: dict[str, asyncio.Future[object]] = {}

    def set_msg_publisher(self, publisher: MessagePublisher | None) -> None:
        """Inject the bus publisher used for ``bus.ai_review_*`` topics.

        The FastAPI lifespan calls this once the shared ZMQ PUB socket is
        available; tests pass a fake publisher (or ``None`` to clear). Decoupling
        socket ownership from the singleton keeps the service trivially testable
        without ZMQ.

        Args:
            publisher: Configured ``MessagePublisher`` or ``None`` to clear.
        """
        self._msg_publisher = publisher

    @property
    def msg_publisher(self) -> MessagePublisher | None:
        """Expose the injected publisher for tests + diagnostics.

        Read-only by design — production code paths route through
        :meth:`submit_decision` / reaper helpers that publish under their own
        post-commit invariants.

        Returns:
            The currently injected ``MessagePublisher`` or ``None``.
        """
        return self._msg_publisher

    def register_future(self, review_public_id: str, fut: asyncio.Future[object]) -> None:
        """Register a future that the strategy is awaiting on.

        Called by ``StrategyContext.create_ai_review`` BEFORE
        :meth:`create_review` publishes ``bus.ai_review_request``, so the
        listener side never sees a decision it can't deliver. Re-registering
        the same id replaces the previous handle: the most recent waiter wins,
        which matches the Plan D §8 retry-on-restart contract where a
        reconnecting strategy is the only legitimate re-registrant.

        Args:
            review_public_id: UUID7 of the ``ai_reviews`` row.
            fut: ``asyncio.Future`` the strategy is awaiting.
        """
        self._futures[review_public_id] = fut

    def unregister_future(self, review_public_id: str) -> None:
        """Drop a future from the registry.

        Idempotent — the await-loop calls this in its ``finally`` after either
        normal resolution or timeout, and the reaper / supersede paths call it
        again as a safety net.

        Args:
            review_public_id: UUID7 of the ``ai_reviews`` row to forget.
        """
        self._futures.pop(review_public_id, None)

    def get_future(self, review_public_id: str) -> asyncio.Future[object] | None:
        """Look up a future without removing it.

        Returns ``None`` when the review id is unknown — typical in
        bus-listener code paths where decisions for already-resolved or
        cross-instance reviews land on this backend; the listener treats
        ``None`` as a no-op.

        Args:
            review_public_id: UUID7 of the ``ai_reviews`` row.

        Returns:
            The registered future or ``None`` if the id is unknown.
        """
        return self._futures.get(review_public_id)

    async def create_review(
        self,
        request: AiReviewCreateRequest,
        *,
        repo: Repository,
        now: datetime | None = None,
        policy: AiReviewAdmissionPolicy = _DEFAULT_AI_REVIEW_ADMISSION_POLICY,
    ) -> AiReviewCreated:
        """Plan A v1.4 Q10 admission control + Plan D §3.1 INSERT.

        Composes :meth:`Repository.list_eligible_delegates_for_ai_review`
        (operator + scope + liveness filter) with
        :meth:`Repository.claim_and_insert_ai_review` (atomic CAS claim
        on ``ai_delegates.active_reviews_count`` + INSERT of the review
        row + ``created`` audit event in one transaction). The
        ``signal_snapshot_hash`` is computed from ``request.signal_envelope``
        so the audit trail can verify the envelope a downstream consumer
        sees matches the one admission control resolved on.

        Bus publish of ``bus.ai_review_request`` is intentionally NOT
        performed here — the publisher slot exists on the singleton but
        the listener side lands in the next chunk (Plan D Phase 1
        item 2 ``supersede_review`` + reaper + scanner). Until the
        listener exists the publish would be a noisy no-op against the
        empty bus topology.

        Args:
            request: Strategy-side payload bundling scope identifiers
                + signal envelope + instrument metadata + deadline +
                bus origin (session_id / sequence_id).
            repo: Repository handle (single-transaction caller context).
            now: Optional override for the wall-clock; tests inject a
                fixed value so the deadline + audit timestamps are
                deterministic.
            policy: Liveness + fanout windows. Defaults to the Plan A
                v1.4 cross-plan locks (15s heartbeat / 30s fanout);
                tests override for fast-clock scenarios.

        Returns:
            :class:`AiReviewCreated` with the freshly inserted
            ``review_public_id`` and the
            ``selected_delegate_public_id`` admission control
            picked.

        Raises:
            NoLiveDelegateError: No eligible AI delegate is live within
                the heartbeat window for the operator + wallet +
                instrument scope.
            DelegateBusyError: Eligible delegates exist but every one
                already has an in-flight review (Q10 caps each at one).
            SignalEnvelopeTooLargeError: ``request.signal_envelope``
                serialises to more than :data:`MAX_SIGNAL_ENVELOPE_BYTES`
                of canonical JSON (Plan A v1.4 risk-register guard).
            ValueError: ``request.signal_envelope`` contains
                non-finite floats (``NaN`` / ``Infinity``) — not valid
                JSON, would corrupt audit-trail reconstruction.
        """
        canonical_envelope = _serialize_signal_envelope_canonical(request.signal_envelope)
        if len(canonical_envelope) > MAX_SIGNAL_ENVELOPE_BYTES:
            raise SignalEnvelopeTooLargeError(
                f"signal_envelope canonical size {len(canonical_envelope)} bytes "
                f"exceeds {MAX_SIGNAL_ENVELOPE_BYTES}-byte cap (Plan A v1.4)."
            )
        wall_clock = now if now is not None else datetime.now(UTC)
        candidates = await repo.list_eligible_delegates_for_ai_review(
            operator_public_id=request.operator_public_id,
            wallet_public_id=request.wallet_public_id,
            instrument_public_id=request.instrument_public_id,
            heartbeat_window_seconds=policy.heartbeat_window_seconds,
            as_of=wall_clock,
        )
        if not candidates:
            raise NoLiveDelegateError(
                f"No live AI delegate eligible for "
                f"operator={request.operator_public_id} "
                f"wallet={request.wallet_public_id} "
                f"instrument={request.instrument_public_id} "
                f"within {policy.heartbeat_window_seconds}s heartbeat window."
            )

        review_public_id = str(uuid7())
        event_public_id = str(uuid7())
        envelope_hash = hashlib.sha256(canonical_envelope).hexdigest()
        deadline = wall_clock + timedelta(seconds=request.deadline_seconds)
        fanout_after = wall_clock + timedelta(seconds=policy.fanout_after_seconds)
        candidate_ids = [candidate["public_id"] for candidate in candidates]

        review_data: AiReviewInsertRow = {
            "public_id": review_public_id,
            "session_id": request.session_id,
            "sequence_id": request.sequence_id,
            "user_public_id": request.user_public_id,
            "operator_public_id": request.operator_public_id,
            "wallet_public_id": request.wallet_public_id,
            "instrument_public_id": request.instrument_public_id,
            "strategy_public_id": request.strategy_public_id,
            "selected_delegate_public_id": candidate_ids[0],
            "status": AiReviewStatusEnum.PENDING.value,
            "signal_envelope": request.signal_envelope,
            "signal_snapshot_hash": envelope_hash,
            "instrument_metadata": request.instrument_metadata,
            "deadline": deadline,
            "fanout_after": fanout_after,
            "dispatch_version": 0,
            "created_at": wall_clock,
            "updated_at": wall_clock,
        }
        event_data: AiReviewEventInsertRow = {
            "public_id": event_public_id,
            "review_public_id": review_public_id,
            "event_type": AiReviewEventTypeEnum.CREATED.value,
            "actor_delegate_public_id": None,
            "previous_status": None,
            "new_status": AiReviewStatusEnum.PENDING.value,
            "payload": {
                "signal_snapshot_hash": envelope_hash,
                "dispatch_version": 0,
            },
            "occurred_at": wall_clock,
        }

        selected = await repo.claim_and_insert_ai_review(
            candidate_delegate_public_ids=candidate_ids,
            review_data=review_data,
            event_data=event_data,
            now=wall_clock,
        )
        if selected is None:
            raise DelegateBusyError(
                f"All {len(candidate_ids)} eligible delegate(s) busy for "
                f"operator={request.operator_public_id} "
                f"wallet={request.wallet_public_id} "
                f"instrument={request.instrument_public_id}."
            )
        logger.info(
            "ai_review created",
            review_public_id=review_public_id,
            selected_delegate_public_id=selected,
            candidate_count=len(candidate_ids),
        )
        return AiReviewCreated(
            review_public_id=review_public_id,
            selected_delegate_public_id=selected,
        )

    async def submit_decision(
        self,
        *,
        review_public_id: str,
        caller_user_public_id: str,
        decision: AiReviewDecisionEnum,
        rationale: str | None,
        repo: Repository,
        scope_grant_service: ScopeGrantService,
        now: datetime | None = None,
    ) -> AiReviewDecisionResult:
        """Submit an AI delegate's decision; Plan D §3.2 nine-step transaction.

        Resolves the caller's ``ai_delegates`` row, confirms the review
        exists and is within the caller's scope grant, branches on
        terminal-state shortcuts (idempotent retry vs peer-won),
        runs the Q9 step 3.5 inline timeout when the deadline has
        already elapsed, then performs the atomic CAS resolve + audit
        event append + Q10 counter decrement.

        Args:
            review_public_id: UUID7 of the ``ai_reviews`` row.
            caller_user_public_id: ``users.public_id`` of the AI delegate
                user submitting the decision; resolved to
                ``ai_delegates.public_id`` via the operational side-table.
            decision: ``APPROVE`` or ``REJECT``.
            rationale: Optional free-text (≤4096 chars; caller validates
                before reaching this method).
            repo: Repository handle. Passed in so the MCP tool keeps the
                caller's transactional context.
            scope_grant_service: Scope-check service. Passed in so the
                MCP tool's ``Depends`` wiring is the source of truth.
            now: Optional override for the transaction wall-clock; tests
                inject a fixed value so the late-decision shortcut and
                resolved_at columns are deterministic.

        Returns:
            :class:`AiReviewDecisionResult` envelope.
        """
        wall_clock = now if now is not None else datetime.now(UTC)
        delegate_row = await repo.get_ai_delegate_by_user_public_id(caller_user_public_id)
        if delegate_row is None:
            return AiReviewDecisionResult(
                error_code=ERROR_NOT_AUTHORIZED,
                message="Caller is not registered as an AI delegate.",
                status=None,
                resolution_mode=None,
                dispatch_version=None,
                details={"caller_user_public_id": caller_user_public_id},
            )
        delegate_public_id = delegate_row["public_id"]

        review = await repo.get_ai_review(review_public_id)
        if review is None:
            return AiReviewDecisionResult(
                error_code=ERROR_REVIEW_NOT_FOUND,
                message="No review with that id.",
                status=None,
                resolution_mode=None,
                dispatch_version=None,
                details={"review_public_id": review_public_id},
            )

        scope_ok = await scope_grant_service.has_grant_for_delegate(
            delegate_public_id=delegate_public_id,
            wallet_public_id=review["wallet_public_id"],
            instrument_public_id=review["instrument_public_id"],
            as_of=wall_clock,
        )
        if not scope_ok:
            return AiReviewDecisionResult(
                error_code=ERROR_NOT_AUTHORIZED,
                message="Delegate has no scope grant for this review.",
                status=AiReviewStatusEnum(review["status"]),
                resolution_mode=(
                    AiReviewResolutionModeEnum(review["resolution_mode"])
                    if review["resolution_mode"] is not None
                    else None
                ),
                dispatch_version=int(review["dispatch_version"]),
                details={
                    "wallet_public_id": review["wallet_public_id"],
                    "instrument_public_id": review["instrument_public_id"],
                },
            )

        if review["status"] in _TERMINAL_STATUSES:
            return self._terminal_state_envelope(
                review=review,
                delegate_public_id=delegate_public_id,
                decision=decision,
            )

        if review["deadline"] <= wall_clock:
            timeout_result = await repo.atomic_timeout_ai_review(
                review_public_id=review_public_id,
                now=wall_clock,
            )
            if timeout_result is not None:
                await repo.insert_ai_review_event(
                    {
                        "public_id": str(uuid7()),
                        "review_public_id": review_public_id,
                        "event_type": AiReviewEventTypeEnum.TIMEOUT_MARKED.value,
                        "actor_delegate_public_id": None,
                        "previous_status": timeout_result["previous_status"],
                        "new_status": AiReviewStatusEnum.TIMEOUT.value,
                        "payload": {"trigger": "submit_decision_late"},
                        "occurred_at": wall_clock,
                    }
                )
                await repo.decrement_delegate_active_count_for_review(
                    review_public_id=review_public_id,
                    selected_delegate_public_id=timeout_result["selected_delegate_public_id"],
                    now=wall_clock,
                )
            return AiReviewDecisionResult(
                error_code=ERROR_REVIEW_EXPIRED,
                message="Deadline elapsed before the decision arrived.",
                status=AiReviewStatusEnum.TIMEOUT,
                resolution_mode=AiReviewResolutionModeEnum.TIMEOUT_NO_RESPONSE,
                dispatch_version=int(review["dispatch_version"]),
                details={"deadline": review["deadline"].isoformat()},
            )

        new_status = (
            AiReviewStatusEnum.RESOLVED_APPROVED
            if decision == AiReviewDecisionEnum.APPROVE
            else AiReviewStatusEnum.RESOLVED_REJECTED
        )
        resolution_mode = self._resolution_mode_for(
            previous_status=review["status"],
            selected_delegate_public_id=review["selected_delegate_public_id"],
            responding_delegate_public_id=delegate_public_id,
        )
        atomic = await repo.atomic_resolve_ai_review(
            review_public_id=review_public_id,
            decision=decision.value,
            responding_delegate_public_id=delegate_public_id,
            rationale=rationale,
            resolution_mode=resolution_mode.value,
            new_status=new_status.value,
            now=wall_clock,
        )
        if atomic is None:
            fresh = await repo.get_ai_review(review_public_id)
            return self._terminal_state_envelope(
                review=fresh if fresh is not None else review,
                delegate_public_id=delegate_public_id,
                decision=decision,
            )

        await repo.insert_ai_review_event(
            {
                "public_id": str(uuid7()),
                "review_public_id": review_public_id,
                "event_type": AiReviewEventTypeEnum.DECISION_RECORDED.value,
                "actor_delegate_public_id": delegate_public_id,
                "previous_status": atomic["previous_status"],
                "new_status": new_status.value,
                "payload": {
                    "decision": decision.value,
                    "rationale": rationale,
                },
                "occurred_at": wall_clock,
            }
        )
        await repo.decrement_delegate_active_count_for_review(
            review_public_id=review_public_id,
            selected_delegate_public_id=atomic["selected_delegate_public_id"],
            now=wall_clock,
        )
        logger.info(
            "ai_review decision recorded",
            review_public_id=review_public_id,
            decision=decision.value,
            resolution_mode=resolution_mode.value,
        )
        return AiReviewDecisionResult(
            error_code=None,
            message="Decision recorded.",
            status=new_status,
            resolution_mode=resolution_mode,
            dispatch_version=int(atomic["dispatch_version"]),
            details={"previous_status": atomic["previous_status"]},
        )

    def _terminal_state_envelope(
        self,
        *,
        review: AiReviewRow,
        delegate_public_id: str,
        decision: AiReviewDecisionEnum,
    ) -> AiReviewDecisionResult:
        """Build the envelope returned when the row is already terminal.

        Disambiguates idempotent-retry (same delegate, same decision)
        from peer-resolved, so the caller can tell the difference between
        "your previous request landed" and "someone else got there first".
        """
        status_enum = AiReviewStatusEnum(review["status"])
        resolution_mode_value = review["resolution_mode"]
        resolution_mode = (
            AiReviewResolutionModeEnum(resolution_mode_value)
            if resolution_mode_value is not None
            else None
        )
        dispatch_version = int(review["dispatch_version"])
        recorded_decision = review["decision"]
        responding = review["responding_delegate_public_id"]
        same_caller = responding == delegate_public_id
        same_decision = recorded_decision is not None and recorded_decision == decision.value
        if same_caller and same_decision:
            return AiReviewDecisionResult(
                error_code=ERROR_DECISION_ALREADY_RECORDED,
                message="Decision already recorded; idempotent retry.",
                status=status_enum,
                resolution_mode=resolution_mode,
                dispatch_version=dispatch_version,
                details={"decision": decision.value},
            )
        return AiReviewDecisionResult(
            error_code=ERROR_PEER_RESOLVED,
            message="Review already resolved by another decision or the reaper.",
            status=status_enum,
            resolution_mode=resolution_mode,
            dispatch_version=dispatch_version,
            details={
                "responding_delegate_public_id": responding,
                "recorded_decision": recorded_decision,
            },
        )

    async def timeout_review(
        self,
        *,
        review_public_id: str,
        repo: Repository,
        now: datetime | None = None,
    ) -> bool:
        """Plan D §3 + §8 inline timeout: pending/fanout_dispatched -> timeout.

        Called by :func:`create_ai_review_and_await` (Plan D §8) when
        the strategy's deadline elapses with the row still
        non-terminal. Mirrors :meth:`supersede_review` shape — atomic
        CAS UPDATE + ``timeout_marked`` audit event + Q10 v1.2 counter
        decrement — with the resolution_mode set to
        ``timeout_no_response``.

        Args:
            review_public_id: UUID7 of the ``ai_reviews`` row.
            repo: Repository handle.
            now: Optional wall-clock override for deterministic tests.

        Returns:
            ``True`` when this call won the CAS and the row
            transitioned; ``False`` when a peer (decision / reaper /
            supersede) had already transitioned the row.
        """
        wall_clock = now if now is not None else datetime.now(UTC)
        atomic = await repo.atomic_timeout_ai_review(
            review_public_id=review_public_id, now=wall_clock
        )
        if atomic is None:
            return False
        await repo.insert_ai_review_event(
            {
                "public_id": str(uuid7()),
                "review_public_id": review_public_id,
                "event_type": AiReviewEventTypeEnum.TIMEOUT_MARKED.value,
                "actor_delegate_public_id": None,
                "previous_status": atomic["previous_status"],
                "new_status": AiReviewStatusEnum.TIMEOUT.value,
                "payload": {"trigger": "strategy_await_loop"},
                "occurred_at": wall_clock,
            }
        )
        await repo.decrement_delegate_active_count_for_review(
            review_public_id=review_public_id,
            selected_delegate_public_id=atomic["selected_delegate_public_id"],
            now=wall_clock,
        )
        logger.info(
            "ai_review timeout (strategy await loop)",
            review_public_id=review_public_id,
        )
        return True

    async def supersede_review(
        self,
        *,
        review_public_id: str,
        reason: str,
        repo: Repository,
        now: datetime | None = None,
    ) -> bool:
        """Plan D §3 strategy-abandon path: pending/fanout_dispatched -> superseded.

        Atomically transitions the row to ``superseded`` /
        ``superseded_by_strategy``, appends a ``superseded`` audit
        event with the reason, and decrements the
        ``ai_delegates.active_reviews_count`` exactly once via the
        Q10 v1.2 ``counter_decremented_at`` CAS primitive shared with
        :meth:`submit_decision` and :meth:`_reaper_tick`.

        Args:
            review_public_id: UUID7 of the ``ai_reviews`` row to
                supersede.
            reason: Free-text rationale stored on the audit-event
                payload (no length cap enforced here — strategy code
                is internal).
            repo: Repository handle (single-transaction caller
                context).
            now: Optional override for the wall-clock; tests inject a
                fixed value so the resolved_at + audit timestamps are
                deterministic.

        Returns:
            ``True`` when this call won the CAS and the row
            transitioned to terminal; ``False`` when a peer (a
            decision, the reaper, or another supersede) had already
            transitioned the row.
        """
        wall_clock = now if now is not None else datetime.now(UTC)
        atomic = await repo.atomic_supersede_ai_review(
            review_public_id=review_public_id, now=wall_clock
        )
        if atomic is None:
            return False
        await repo.insert_ai_review_event(
            {
                "public_id": str(uuid7()),
                "review_public_id": review_public_id,
                "event_type": AiReviewEventTypeEnum.SUPERSEDED.value,
                "actor_delegate_public_id": None,
                "previous_status": atomic["previous_status"],
                "new_status": AiReviewStatusEnum.SUPERSEDED.value,
                "payload": {"reason": reason},
                "occurred_at": wall_clock,
            }
        )
        await repo.decrement_delegate_active_count_for_review(
            review_public_id=review_public_id,
            selected_delegate_public_id=atomic["selected_delegate_public_id"],
            now=wall_clock,
        )
        logger.info(
            "ai_review superseded",
            review_public_id=review_public_id,
            reason=reason,
        )
        return True

    async def _reaper_tick(self, *, repo: Repository, now: datetime | None = None) -> int:
        """Plan D §3.3 single-tick reaper iteration.

        Snapshots up to N expired pending/fanout_dispatched reviews,
        then per-row drives the existing
        :meth:`Repository.atomic_timeout_ai_review` CAS + audit-event
        + counter-decrement primitives shared with
        :meth:`submit_decision`. Returns the number of rows that won
        the per-row CAS this tick (rows that lost — because a peer
        decision or earlier reaper landed first — are silently
        skipped, matching the spec's "drop-the-lease" guarantee).

        Args:
            repo: Repository handle.
            now: Optional override for the wall-clock.

        Returns:
            Number of rows successfully transitioned to ``timeout`` by
            this tick.
        """
        wall_clock = now if now is not None else datetime.now(UTC)
        candidates = await repo.list_expired_pending_reviews(now=wall_clock)
        transitioned = 0
        for candidate in candidates:
            atomic = await repo.atomic_timeout_ai_review(
                review_public_id=candidate["public_id"], now=wall_clock
            )
            if atomic is None:
                continue
            await repo.insert_ai_review_event(
                {
                    "public_id": str(uuid7()),
                    "review_public_id": candidate["public_id"],
                    "event_type": AiReviewEventTypeEnum.TIMEOUT_MARKED.value,
                    "actor_delegate_public_id": None,
                    "previous_status": atomic["previous_status"],
                    "new_status": AiReviewStatusEnum.TIMEOUT.value,
                    "payload": {"trigger": "reaper_tick"},
                    "occurred_at": wall_clock,
                }
            )
            await repo.decrement_delegate_active_count_for_review(
                review_public_id=candidate["public_id"],
                selected_delegate_public_id=atomic["selected_delegate_public_id"],
                now=wall_clock,
            )
            transitioned += 1
        if transitioned > 0:
            logger.info("ai_review reaper tick", transitioned=transitioned)
        return transitioned

    async def _offline_scanner_tick(
        self,
        *,
        repo: Repository,
        now: datetime | None = None,
        heartbeat_window_seconds: int = DEFAULT_HEARTBEAT_WINDOW_SECONDS,
    ) -> int:
        """Plan D §3.4 single-tick Layer 2 offline scanner iteration.

        Snapshots up to N pending reviews whose ``fanout_after`` has
        elapsed AND whose selected delegate has gone silent past the
        heartbeat window, then drives the per-row atomic
        ``pending -> fanout_dispatched`` CAS + ``fanout_dispatched``
        audit event for each. Returns the number of fanouts dispatched
        this tick.

        Args:
            repo: Repository handle.
            now: Optional override for the wall-clock.
            heartbeat_window_seconds: Liveness window passed through
                to the eligibility query.

        Returns:
            Number of pending reviews whose CAS won this tick.
        """
        wall_clock = now if now is not None else datetime.now(UTC)
        candidates = await repo.list_offline_pending_reviews(
            now=wall_clock, heartbeat_window_seconds=heartbeat_window_seconds
        )
        return await self._dispatch_fanout_for_candidates(
            candidates=candidates,
            repo=repo,
            now=wall_clock,
            trigger="offline_scanner_tick",
        )

    async def _delegate_offline_tick(
        self,
        *,
        delegate_public_id: str,
        repo: Repository,
        now: datetime | None = None,
    ) -> int:
        """Plan D §3.5 fast-path equivalent of the §3.4 scanner.

        Scans only the pending rows whose
        ``selected_delegate_public_id`` matches the freshly-offline
        delegate, then drives the same atomic fanout-dispatch CAS as
        the Layer 2 scanner. Idempotent vs §3.4: a row that the
        scanner already transitioned is skipped because the CAS
        predicate is ``status='pending'``.

        Args:
            delegate_public_id: ``ai_delegates.public_id`` of the
                delegate whose ``bus.delegate_offline`` event triggered
                the call.
            repo: Repository handle.
            now: Optional override for the wall-clock. Callers from the
                bus subscriber pass ``msg.last_seen_at`` so the
                ``fanout_after`` gate matches the instant the delegate
                actually went offline; reviews whose ``fanout_after``
                is still in the future are deferred to the §3.4 Layer 2
                scanner per the :class:`DelegateOfflineData` schema
                contract.

        Returns:
            Number of pending reviews whose CAS won this fast-path
            invocation.
        """
        wall_clock = now if now is not None else datetime.now(UTC)
        candidates = await repo.list_pending_reviews_for_delegate(
            selected_delegate_public_id=delegate_public_id, now=wall_clock
        )
        return await self._dispatch_fanout_for_candidates(
            candidates=candidates,
            repo=repo,
            now=wall_clock,
            trigger="delegate_offline_bus",
        )

    async def _dispatch_fanout_for_candidates(
        self,
        *,
        candidates: list[PendingReviewSummary],
        repo: Repository,
        now: datetime,
        trigger: str,
    ) -> int:
        """Common per-candidate CAS + audit-event loop for §3.4 / §3.5.

        Both the Layer 2 scanner and the §3.5 fast-path share the same
        per-row dispatch shape: atomic CAS UPDATE pending ->
        fanout_dispatched (incrementing ``dispatch_version``), then
        append a ``fanout_dispatched`` audit-event row with the
        trigger source on the payload. Extracted into a helper so the
        two callers can't drift on the audit-event shape.
        """
        dispatched = 0
        for candidate in candidates:
            new_version = await repo.atomic_dispatch_fanout(
                review_public_id=candidate["public_id"], now=now
            )
            if new_version is None:
                continue
            await repo.insert_ai_review_event(
                {
                    "public_id": str(uuid7()),
                    "review_public_id": candidate["public_id"],
                    "event_type": AiReviewEventTypeEnum.FANOUT_DISPATCHED.value,
                    "actor_delegate_public_id": None,
                    "previous_status": AiReviewStatusEnum.PENDING.value,
                    "new_status": AiReviewStatusEnum.FANOUT_DISPATCHED.value,
                    "payload": {
                        "trigger": trigger,
                        "dispatch_version": new_version,
                    },
                    "occurred_at": now,
                }
            )
            dispatched += 1
        if dispatched > 0:
            logger.info("ai_review fanout dispatched", trigger=trigger, count=dispatched)
        return dispatched

    async def handle_caps_violation_bus_message(self, msg: CapsViolationAfterAiApproveData) -> bool:
        """Plan D §3.6 — re-fanout caps-violation events to the WS topic family.

        Subscribes to the internal ``bus.caps_violation_after_ai_approve``
        topic; for each event, publishes the Plan A Q7 / Plan D §4.3
        external topic
        ``ai_reviews.{user_public_id}.{strategy_public_id}.caps_violation``
        so the bridge can surface the rejection on the delegate's UI.

        Best-effort: a missing publisher logs a warning instead of
        raising (mirrors :class:`ScopeGrantService` semantics — a
        singleton spun up before the FastAPI lifespan attached one
        still tolerates the call). A send failure degrades to a
        logged exception so a transient broker hiccup never crashes
        the subscriber loop.

        Args:
            msg: Decoded :class:`CapsViolationAfterAiApproveData`
                payload published by :class:`TradingCapsEnforcer`
                (publisher-side wiring lands in a follow-up chunk).

        Returns:
            ``True`` when the WS event was handed to the publisher,
            ``False`` when the publisher slot was empty.
        """
        if self._msg_publisher is None:
            logger.warning(
                "ai_reviews caps_violation NOT broadcast for review_public_id={}: "
                "AiReviewService publisher unavailable",
                msg.review_public_id,
            )
            return False
        topic = f"ai_reviews.{msg.user_public_id}.{msg.strategy_public_id}.caps_violation"
        try:
            await self._msg_publisher.send(topic, msg)
        except Exception as exc:
            logger.exception(
                "Failed to broadcast ai_reviews caps_violation for review_public_id={}: {}",
                msg.review_public_id,
                exc,
            )
            return False
        return True

    async def handle_delegate_offline_bus_message(
        self, msg: DelegateOfflineData, *, repo: Repository
    ) -> int:
        """Plan D §3.5 ``bus.delegate_offline`` subscriber entry point.

        Wraps :meth:`_delegate_offline_tick` so the ZMQ listener loop
        (wired in a follow-up commit) can dispatch on the message
        envelope without knowing the ``_tick`` argument shape.

        Args:
            msg: Decoded ``bus.delegate_offline`` payload published by
                :class:`WebSocketAuthManager`.
            repo: Repository handle (passed by the listener's per-tick
                wiring).

        Returns:
            Number of pending reviews whose CAS won this fast-path
            invocation (forwarded from
            :meth:`_delegate_offline_tick`).
        """
        return await self._delegate_offline_tick(
            delegate_public_id=msg.delegate_public_id,
            repo=repo,
            now=msg.last_seen_at,
        )

    @staticmethod
    def _resolution_mode_for(
        *,
        previous_status: str,
        selected_delegate_public_id: str,
        responding_delegate_public_id: str,
    ) -> AiReviewResolutionModeEnum:
        """Plan A Q4 — pick the resolution_mode the row's transition implies.

        - ``pending`` + selected==responding -> PICK_ONE_PRIMARY (most common).
        - ``fanout_dispatched`` + selected==responding -> SECONDARY_AFTER_FANOUT
          (selected delegate came back online after fanout fired).
        - ``fanout_dispatched`` + selected!=responding -> FANOUT_FIRST_RESPONDER
          (different eligible delegate won the fanout race).
        """
        if previous_status == AiReviewStatusEnum.PENDING.value:
            return AiReviewResolutionModeEnum.PICK_ONE_PRIMARY
        if responding_delegate_public_id == selected_delegate_public_id:
            return AiReviewResolutionModeEnum.SECONDARY_AFTER_FANOUT
        return AiReviewResolutionModeEnum.FANOUT_FIRST_RESPONDER

    @classmethod
    def get_instance(cls) -> AiReviewService:
        """Return the singleton, creating it on first call.

        Returns:
            The process-wide ``AiReviewService`` singleton.
        """
        if cls._instance is None:
            cls._instance = AiReviewService()
        return cls._instance

    @classmethod
    def clear_instance(cls) -> None:
        """Reset the singleton — test-only seam."""
        cls._instance = None
        cls._initialized = False


