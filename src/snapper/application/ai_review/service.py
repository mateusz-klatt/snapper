def _serialize_signal_envelope_canonical(envelope: JsonObject) -> bytes:
    """Canonical JSON bytes for hashing + size enforcement.

    ``allow_nan=False`` rejects ``NaN`` / ``Infinity`` at this point: those
    values are not valid JSON and round-trip differently between SQLite's
    ``JSON`` text storage and PostgreSQL ``JSONB``, so a downstream
    consumer reconstructing the envelope from the column would see a
    different hash than the one stored on the audit-event payload.
    ``sort_keys=True`` + tight separators give a stable canonical form so
    two equivalent envelopes hash identically regardless of build order.
    """
    return json.dumps(
        envelope,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")


def _signal_envelope_hash(envelope: JsonObject) -> str:
    """Canonical SHA-256 hex digest of the signal envelope.

    Stored in the ``ai_reviews.signal_snapshot_hash`` column AND on the
    ``ai_review_events.created`` payload so a consumer reconstructing the
    audit trail can confirm the envelope it sees matches the one the
    review was created from.
    """
    return hashlib.sha256(_serialize_signal_envelope_canonical(envelope)).hexdigest()


class AiReviewService:
    """Singleton owner of the ``ai_reviews`` state machine + future registry."""

    _instance: AiReviewService | None = None
    _initialized: bool = False

    def __new__(cls) -> AiReviewService:
        """Create or return the singleton instance."""
        if cls._instance is None:
            instance = super().__new__(cls)
            cls._instance = instance
        return cls._instance

    def __init__(self) -> None:
        """Initialise publisher slot + futures registry on first construction."""
        if self._initialized:
            return
        self._initialized = True
        self._msg_publisher: MessagePublisher | None = None
        self._futures: dict[str, asyncio.Future[object]] = {}
        self._pending_resolutions: dict[str, tuple[AiReviewDecisionData, datetime]] = {}
        self._repository_factory: Callable[[], Repository] | None = None
        self._bus_subscriber: ValidatedSubscriber | None = None
        self._bus_zmq_context: zmq.asyncio.Context | None = None
        self._bus_listen_task: asyncio.Task[None] | None = None
        self._bus_running: bool = False
        self._bus_listener_lock: asyncio.Lock = asyncio.Lock()
        self._shard_ownership: ShardOwnership | None = None

    def set_shard_ownership(self, ownership: ShardOwnership | None) -> None:
        """Inject the static-hash partitioning primitive used for multi-instance dedup.

        Plan D Phase 2 #8 — under multi-worker uvicorn (``instance_count > 1``)
        the shared ZMQ XPUB-XSUB broker delivers every internal bus event to
        every worker's :meth:`start_bus_listener`. Most of our handlers are
        already idempotent under that fanout: ``handle_delegate_offline_bus_message``
        drives a per-row CAS, and ``handle_ai_review_decision_bus_message`` looks
        up a process-local Future registry that only the originating worker
        populated. The exception is :meth:`handle_caps_violation_bus_message`,
        which on every dispatch re-publishes a fresh
        ``ai_reviews.{user}.{strategy}.caps_violation`` external WS frame — N
        workers would N-duplicate the frame to every connected subscriber.

        ``ShardOwnership.owns(review_public_id)`` deterministically picks one
        worker per review row to handle the caps-violation re-fanout; non-owners
        skip the publish. ``instance_count == 1`` (default deployment) makes
        :meth:`ShardOwnership.owns` return True unconditionally so behaviour is
        byte-identical to pre-P2-8a single-instance.

        ``None`` clears the seam (test cleanup or pre-lifespan boot). When
        cleared, the caps-violation handler treats the absence as the legacy
        "single-instance" mode and publishes unconditionally — the FastAPI
        lifespan injects the real ``ShardOwnership`` immediately after the
        publisher seam, so production code paths always observe the configured
        primitive once startup completes.

        Args:
            ownership: Configured :class:`ShardOwnership` (built from
                ``settings.coordinator_instance_id`` + ``coordinator_instance_count``)
                or ``None`` to clear.
        """
        self._shard_ownership = ownership

    @property
    def shard_ownership(self) -> ShardOwnership | None:
        """Expose the injected partitioning primitive for tests + diagnostics.

        Returns:
            The currently injected :class:`ShardOwnership` or ``None`` when the
            seam has not been wired yet.
        """
        return self._shard_ownership

    def set_msg_publisher(self, publisher: MessagePublisher | None) -> None:
        """Inject the bus publisher used for ``bus.ai_review_*`` topics.

        The FastAPI lifespan calls this once the shared ZMQ PUB socket is
        available; tests pass a fake publisher (or ``None`` to clear). Decoupling
        socket ownership from the singleton keeps the service trivially testable
        without ZMQ.

        Args:
            publisher: Configured ``MessagePublisher`` or ``None`` to clear.
        """
        self._msg_publisher = publisher

    @property
    def msg_publisher(self) -> MessagePublisher | None:
        """Expose the injected publisher for tests + diagnostics.

        Read-only by design — production code paths route through
        :meth:`submit_decision` / reaper helpers that publish under their own
        post-commit invariants.

        Returns:
            The currently injected ``MessagePublisher`` or ``None``.
        """
        return self._msg_publisher

    def register_future(self, review_public_id: str, fut: asyncio.Future[object]) -> None:
        """Register a future that the strategy is awaiting on.

        Called by the strategy primitive AFTER
        :meth:`create_review` returns the public_id. This creates a
        register-after-create race: a fast delegate could submit a
        decision in the gap between the row's INSERT and our
        register_future call, the bus event would arrive at the
        listener with no future to resolve, and the strategy would
        fall through to the DB-poll fallback path (slower than the
        fast-path but still correct).

        To close that race, the listener stashes any decision it
        receives without a matching future into
        :attr:`_pending_resolutions` (a small bounded cache). On
        register_future we drain the cache: if a decision for this
        ``review_public_id`` arrived before our registration, we
        resolve the future immediately + drop the cache entry. Stale
        entries past
        :data:`_PENDING_RESOLUTION_TTL_SECONDS` get evicted on every
        register_future call so the cache cannot grow unbounded
        even if the strategy crashes between create_review and
        register_future.

        Re-registering the same id replaces the previous handle: the
        most recent waiter wins, which matches the Plan D §8
        retry-on-restart contract where a reconnecting strategy is
        the only legitimate re-registrant.

        Args:
            review_public_id: UUID7 of the ``ai_reviews`` row.
            fut: ``asyncio.Future`` the strategy is awaiting.
        """
        self._futures[review_public_id] = fut
        self._evict_expired_pending_resolutions()
        pending = self._pending_resolutions.pop(review_public_id, None)
        if pending is None:
            return
        cached_event, _ = pending
        if not fut.done():
            fut.set_result(cached_event)
            logger.debug(
                "ai_review fast-path future resolved from pending cache",
                review_public_id=review_public_id,
                decision=cached_event.decision,
            )

    def _evict_expired_pending_resolutions(self) -> None:
        """Drop pending-resolution cache entries past their TTL.

        Bounded-size guarantee even if a strategy crashes between
        :meth:`create_review` and :meth:`register_future`. Called
        opportunistically from :meth:`register_future` +
        :meth:`handle_ai_review_decision_bus_message` so no
        background task is required.
        """
        if not self._pending_resolutions:
            return
        cutoff = datetime.now(UTC) - timedelta(seconds=_PENDING_RESOLUTION_TTL_SECONDS)
        stale = [
            rid
            for rid, (_event, cached_at) in self._pending_resolutions.items()
            if cached_at < cutoff
        ]
        for rid in stale:
            self._pending_resolutions.pop(rid, None)

    def _enforce_pending_resolution_size_cap(self) -> None:
        """Last-resort hard-size cap on the pending-resolution cache.

        TTL eviction is opportunistic so under normal conditions the
        cache stays well under :data:`_PENDING_RESOLUTION_MAX_ENTRIES`.
        Defends against a runaway publisher emitting events for
        review_public_ids no strategy ever registers — without this
        cap the dict could grow without bound between TTL sweeps if
        all entries are still within their 30s window.

        Drop-oldest semantics: Python ``dict`` preserves insertion
        order, so popping from the front evicts the OLDEST entries
        first and the freshest events survive longer. Logs a single
        warning per overflow batch so operators see the signal
        without busy-spamming the log.
        """
        overflow = len(self._pending_resolutions) - _PENDING_RESOLUTION_MAX_ENTRIES
        if overflow <= 0:
            return
        oldest_keys = list(itertools.islice(self._pending_resolutions, overflow))
        for rid in oldest_keys:
            self._pending_resolutions.pop(rid, None)
        logger.warning(
            "ai_review pending-resolution cache overflow",
            evicted=len(oldest_keys),
            cap=_PENDING_RESOLUTION_MAX_ENTRIES,
        )

    def unregister_future(self, review_public_id: str) -> None:
        """Drop a future from the registry + any pending-resolution cache entry.

        Idempotent — the await-loop calls this in its ``finally`` after either
        normal resolution or timeout, and the reaper / supersede paths call it
        again as a safety net. Also drops any matching entry from
        :attr:`_pending_resolutions` so a strategy that already saw its
        outcome via the DB-poll fallback doesn't leave a stale event in the
        cache (the TTL would clean it up eventually, but explicit removal
        keeps the cache tight).

        Args:
            review_public_id: UUID7 of the ``ai_reviews`` row to forget.
        """
        self._futures.pop(review_public_id, None)
        self._pending_resolutions.pop(review_public_id, None)

    def get_future(self, review_public_id: str) -> asyncio.Future[object] | None:
        """Look up a future without removing it.

        Returns ``None`` when the review id is unknown — typical in
        bus-listener code paths where decisions for already-resolved or
        cross-instance reviews land on this backend; the listener treats
        ``None`` as a no-op.

        Args:
            review_public_id: UUID7 of the ``ai_reviews`` row.

        Returns:
            The registered future or ``None`` if the id is unknown.
        """
        return self._futures.get(review_public_id)

    async def create_review(
        self,
        request: AiReviewCreateRequest,
        *,
        repo: Repository,
        now: datetime | None = None,
        policy: AiReviewAdmissionPolicy = _DEFAULT_AI_REVIEW_ADMISSION_POLICY,
    ) -> AiReviewCreated:
        """Plan A v1.4 Q10 admission control + Plan D §3.1 INSERT.

        Composes :meth:`Repository.list_eligible_delegates_for_ai_review`
        (operator + scope + liveness filter) with
        :meth:`Repository.claim_and_insert_ai_review` (atomic CAS claim
        on ``ai_delegates.active_reviews_count`` + INSERT of the review
        row + ``created`` audit event in one transaction). The
        ``signal_snapshot_hash`` is computed from ``request.signal_envelope``
        so the audit trail can verify the envelope a downstream consumer
        sees matches the one admission control resolved on.

        Bus publish of ``bus.ai_review_request`` is intentionally NOT
        performed here — the publisher slot exists on the singleton but
        the listener side lands in the next chunk (Plan D Phase 1
        item 2 ``supersede_review`` + reaper + scanner). Until the
        listener exists the publish would be a noisy no-op against the
        empty bus topology.

        Args:
            request: Strategy-side payload bundling scope identifiers
                + signal envelope + instrument metadata + deadline +
                bus origin (session_id / sequence_id).
            repo: Repository handle (single-transaction caller context).
            now: Optional override for the wall-clock; tests inject a
                fixed value so the deadline + audit timestamps are
                deterministic.
            policy: Liveness + fanout windows. Defaults to the Plan A
                v1.4 cross-plan locks (15s heartbeat / 30s fanout);
                tests override for fast-clock scenarios.

        Returns:
            :class:`AiReviewCreated` with the freshly inserted
            ``review_public_id`` and the
            ``selected_delegate_public_id`` admission control
            picked.

        Raises:
            NoLiveDelegateError: No eligible AI delegate is live within
                the heartbeat window for the operator + wallet +
                instrument scope.
            DelegateBusyError: Eligible delegates exist but every one
                already has an in-flight review (Q10 caps each at one).
            SignalEnvelopeTooLargeError: ``request.signal_envelope``
                serialises to more than :data:`MAX_SIGNAL_ENVELOPE_BYTES`
                of canonical JSON (Plan A v1.4 risk-register guard).
            ValueError: ``request.signal_envelope`` contains
                non-finite floats (``NaN`` / ``Infinity``) — not valid
                JSON, would corrupt audit-trail reconstruction.
        """
        canonical_envelope = _serialize_signal_envelope_canonical(request.signal_envelope)
        if len(canonical_envelope) > MAX_SIGNAL_ENVELOPE_BYTES:
            raise SignalEnvelopeTooLargeError(
                f"signal_envelope canonical size {len(canonical_envelope)} bytes "
                f"exceeds {MAX_SIGNAL_ENVELOPE_BYTES}-byte cap (Plan A v1.4)."
            )
        wall_clock = now if now is not None else datetime.now(UTC)
        candidates = await repo.list_eligible_delegates_for_ai_review(
            operator_public_id=request.operator_public_id,
            wallet_public_id=request.wallet_public_id,
            instrument_public_id=request.instrument_public_id,
            heartbeat_window_seconds=policy.heartbeat_window_seconds,
            as_of=wall_clock,
        )
        if not candidates:
            raise NoLiveDelegateError(
                f"No live AI delegate eligible for "
                f"operator={request.operator_public_id} "
                f"wallet={request.wallet_public_id} "
                f"instrument={request.instrument_public_id} "
                f"within {policy.heartbeat_window_seconds}s heartbeat window."
            )

        review_public_id = str(uuid7())
        event_public_id = str(uuid7())
        envelope_hash = hashlib.sha256(canonical_envelope).hexdigest()
        deadline = wall_clock + timedelta(seconds=request.deadline_seconds)
        fanout_after = wall_clock + timedelta(seconds=policy.fanout_after_seconds)
        candidate_ids = [candidate["public_id"] for candidate in candidates]

        review_data: AiReviewInsertRow = {
            "public_id": review_public_id,
            "session_id": request.session_id,
            "sequence_id": request.sequence_id,
            "user_public_id": request.user_public_id,
            "operator_public_id": request.operator_public_id,
            "wallet_public_id": request.wallet_public_id,
            "instrument_public_id": request.instrument_public_id,
            "strategy_public_id": request.strategy_public_id,
            "selected_delegate_public_id": candidate_ids[0],
            "status": AiReviewStatusEnum.PENDING.value,
            "signal_envelope": request.signal_envelope,
            "signal_snapshot_hash": envelope_hash,
            "instrument_metadata": request.instrument_metadata,
            "deadline": deadline,
            "fanout_after": fanout_after,
            "dispatch_version": 0,
            "created_at": wall_clock,
            "updated_at": wall_clock,
        }
        event_data: AiReviewEventInsertRow = {
            "public_id": event_public_id,
            "review_public_id": review_public_id,
            "event_type": AiReviewEventTypeEnum.CREATED.value,
            "actor_delegate_public_id": None,
            "previous_status": None,
            "new_status": AiReviewStatusEnum.PENDING.value,
            "payload": {
                "signal_snapshot_hash": envelope_hash,
                "dispatch_version": 0,
            },
            "occurred_at": wall_clock,
        }

        selected = await repo.claim_and_insert_ai_review(
            candidate_delegate_public_ids=candidate_ids,
            review_data=review_data,
            event_data=event_data,
            now=wall_clock,
        )
        if selected is None:
            raise DelegateBusyError(
                f"All {len(candidate_ids)} eligible delegate(s) busy for "
                f"operator={request.operator_public_id} "
                f"wallet={request.wallet_public_id} "
                f"instrument={request.instrument_public_id}."
            )
        logger.info(
            "ai_review created",
            review_public_id=review_public_id,
            selected_delegate_public_id=selected,
            candidate_count=len(candidate_ids),
        )
        await self._publish_request_external_frame(
            review_public_id=review_public_id,
            user_public_id=request.user_public_id,
            strategy_public_id=request.strategy_public_id,
            wallet_public_id=request.wallet_public_id,
            instrument_public_id=request.instrument_public_id,
            selected_delegate_public_id=selected,
            deadline=deadline,
            signal_envelope=request.signal_envelope,
            instrument_metadata=request.instrument_metadata,
            wall_clock=wall_clock,
        )
        return AiReviewCreated(
            review_public_id=review_public_id,
            selected_delegate_public_id=selected,
        )

    async def _publish_request_external_frame(
        self,
        *,
        review_public_id: str,
        user_public_id: str,
        strategy_public_id: str,
        wallet_public_id: str,
        instrument_public_id: str,
        selected_delegate_public_id: str,
        deadline: datetime,
        signal_envelope: JsonObject,
        instrument_metadata: JsonObject,
        wall_clock: datetime,
    ) -> None:
        """Plan A §4.2 / Q16 — emit external WS frame for the new review.

        Best-effort + race-safe (mirrors :meth:`_publish_decision_bus_event`
        + :meth:`TradingCapsEnforcer._publish_caps_violation_after_ai_approve`):
        the publisher reference is captured into a local BEFORE any
        await so a concurrent shutdown clearing the slot cannot null
        it mid-helper, and the entire publish branch is wrapped in a
        single try/except so NO failure (broker hiccup, validator
        reject, transport error) can replace the post-commit
        :class:`AiReviewCreated` envelope the caller is about to
        return. The DB-side claim+insert is the primary contract; the
        WS fanout is auxiliary. A lost frame degrades to the
        delegate's REST fallback poll on
        ``GET /api/ai-reviews/pending``.

        Args:
            review_public_id: Just-inserted review id.
            user_public_id: Owner of the consulting strategy.
            strategy_public_id: Origin strategy.
            wallet_public_id: Wallet the strategy would trade on.
            instrument_public_id: Instrument the strategy is consulting on.
            selected_delegate_public_id: Q10 admission control's pick.
            deadline: Decision deadline.
            signal_envelope: Strategy's payload (16KB-bounded by
                :meth:`create_review`).
            instrument_metadata: Strategy-supplied instrument context.
            wall_clock: Creation wall clock — reused as the frame
                timestamp so audit + WS fanout correlate.
        """
        publisher = self._msg_publisher
        if publisher is None:
            logger.warning(
                "ai_reviews request frame NOT broadcast for "
                f"review_public_id={review_public_id}: AiReviewService publisher unavailable"
            )
            return
        topic = f"ai_reviews.{user_public_id}.{strategy_public_id}.request"
        try:
            tracker = publisher.tracker
            payload = AiReviewRequestFrameData(
                public_id=str(uuid7()),
                timestamp=wall_clock,
                session_id=tracker.session_id,
                sequence_id=tracker.next_sequence(topic),
                review_public_id=review_public_id,
                user_public_id=user_public_id,
                strategy_public_id=strategy_public_id,
                wallet_public_id=wallet_public_id,
                instrument_public_id=instrument_public_id,
                selected_delegate_public_id=selected_delegate_public_id,
                deadline=deadline,
                signal_envelope=signal_envelope,
                instrument_metadata=instrument_metadata,
                dispatch_version=0,
            )
            await publisher.send(topic, payload)
        except Exception as publish_exc:
            logger.exception(
                "AiReviewService: failed to broadcast ai_reviews request frame for "
                f"review_public_id={review_public_id}: {publish_exc} "
                "(review row is committed; delegate falls back to REST poll)"
            )

    async def submit_decision(
        self,
        *,
        review_public_id: str,
        caller_user_public_id: str,
        decision: AiReviewDecisionEnum,
        rationale: str | None,
        repo: Repository,
        scope_grant_service: ScopeGrantService,
        now: datetime | None = None,
    ) -> AiReviewDecisionResult:
        """Submit an AI delegate's decision; Plan D §3.2 nine-step transaction.

        Resolves the caller's ``ai_delegates`` row, confirms the review
        exists and is within the caller's scope grant, branches on
        terminal-state shortcuts (idempotent retry vs peer-won),
        runs the Q9 step 3.5 inline timeout when the deadline has
        already elapsed, then performs the atomic CAS resolve + audit
        event append + Q10 counter decrement.

        Args:
            review_public_id: UUID7 of the ``ai_reviews`` row.
            caller_user_public_id: ``users.public_id`` of the AI delegate
                user submitting the decision; resolved to
                ``ai_delegates.public_id`` via the operational side-table.
            decision: ``APPROVE`` or ``REJECT``.
            rationale: Optional free-text (≤4096 chars; caller validates
                before reaching this method).
            repo: Repository handle. Passed in so the MCP tool keeps the
                caller's transactional context.
            scope_grant_service: Scope-check service. Passed in so the
                MCP tool's ``Depends`` wiring is the source of truth.
            now: Optional override for the transaction wall-clock; tests
                inject a fixed value so the late-decision shortcut and
                resolved_at columns are deterministic.

        Returns:
            :class:`AiReviewDecisionResult` envelope.
        """
        wall_clock = now if now is not None else datetime.now(UTC)
        delegate_row = await repo.get_ai_delegate_by_user_public_id(caller_user_public_id)
        if delegate_row is None:
            return AiReviewDecisionResult(
                error_code=ERROR_NOT_AUTHORIZED,
                message="Caller is not registered as an AI delegate.",
                status=None,
                resolution_mode=None,
                dispatch_version=None,
                details={"caller_user_public_id": caller_user_public_id},
            )
        delegate_public_id = delegate_row["public_id"]

        review = await repo.get_ai_review(review_public_id)
        if review is None:
            return AiReviewDecisionResult(
                error_code=ERROR_REVIEW_NOT_FOUND,
                message="No review with that id.",
                status=None,
                resolution_mode=None,
                dispatch_version=None,
                details={"review_public_id": review_public_id},
            )

        scope_ok = await scope_grant_service.has_grant_for_delegate(
            delegate_public_id=delegate_public_id,
            wallet_public_id=review["wallet_public_id"],
            instrument_public_id=review["instrument_public_id"],
            as_of=wall_clock,
        )
        if not scope_ok:
            return AiReviewDecisionResult(
                error_code=ERROR_NOT_AUTHORIZED,
                message="Delegate has no scope grant for this review.",
                status=AiReviewStatusEnum(review["status"]),
                resolution_mode=(
                    AiReviewResolutionModeEnum(review["resolution_mode"])
                    if review["resolution_mode"] is not None
                    else None
                ),
                dispatch_version=int(review["dispatch_version"]),
                details={
                    "wallet_public_id": review["wallet_public_id"],
                    "instrument_public_id": review["instrument_public_id"],
                },
            )

        if review["status"] in _TERMINAL_STATUSES:
            return self._terminal_state_envelope(
                review=review,
                delegate_public_id=delegate_public_id,
                decision=decision,
            )

        if review["deadline"] <= wall_clock:
            await repo.atomic_timeout_review_with_audit_and_counter(
                review_public_id=review_public_id,
                audit_event={
                    "public_id": str(uuid7()),
                    "review_public_id": review_public_id,
                    "event_type": AiReviewEventTypeEnum.TIMEOUT_MARKED.value,
                    "actor_delegate_public_id": None,
                    "previous_status": AiReviewStatusEnum.PENDING.value,
                    "new_status": AiReviewStatusEnum.TIMEOUT.value,
                    "payload": {"trigger": "submit_decision_late"},
                    "occurred_at": wall_clock,
                },
                now=wall_clock,
            )
            return AiReviewDecisionResult(
                error_code=ERROR_REVIEW_EXPIRED,
                message="Deadline elapsed before the decision arrived.",
                status=AiReviewStatusEnum.TIMEOUT,
                resolution_mode=AiReviewResolutionModeEnum.TIMEOUT_NO_RESPONSE,
                dispatch_version=int(review["dispatch_version"]),
                details={"deadline": review["deadline"].isoformat()},
            )

        new_status = (
            AiReviewStatusEnum.RESOLVED_APPROVED
            if decision == AiReviewDecisionEnum.APPROVE
            else AiReviewStatusEnum.RESOLVED_REJECTED
        )
        resolution_mode = self._resolution_mode_for(
            previous_status=review["status"],
            selected_delegate_public_id=review["selected_delegate_public_id"],
            responding_delegate_public_id=delegate_public_id,
        )
        atomic = await repo.atomic_resolve_review_with_audit_and_counter(
            review_public_id=review_public_id,
            decision=decision.value,
            responding_delegate_public_id=delegate_public_id,
            rationale=rationale,
            resolution_mode=resolution_mode.value,
            new_status=new_status.value,
            audit_event={
                "public_id": str(uuid7()),
                "review_public_id": review_public_id,
                "event_type": AiReviewEventTypeEnum.DECISION_RECORDED.value,
                "actor_delegate_public_id": delegate_public_id,
                "previous_status": review["status"],
                "new_status": new_status.value,
                "payload": {
                    "decision": decision.value,
                    "rationale": rationale,
                },
                "occurred_at": wall_clock,
            },
            now=wall_clock,
        )
        if atomic is None:
            fresh = await repo.get_ai_review(review_public_id)
            return self._terminal_state_envelope(
                review=fresh if fresh is not None else review,
                delegate_public_id=delegate_public_id,
                decision=decision,
            )

        logger.info(
            "ai_review decision recorded",
            review_public_id=review_public_id,
            decision=decision.value,
            resolution_mode=resolution_mode.value,
        )
        await self._publish_decision_bus_event(
            review_public_id=review_public_id,
            responding_delegate_public_id=delegate_public_id,
            decision=decision.value,
            new_status=new_status.value,
            resolution_mode=resolution_mode.value,
            dispatch_version=int(atomic["dispatch_version"]),
            wall_clock=wall_clock,
        )
        await self._publish_decision_ack_external_frame(
            review_public_id=review_public_id,
            user_public_id=review["user_public_id"],
            strategy_public_id=review["strategy_public_id"],
            wallet_public_id=review["wallet_public_id"],
            instrument_public_id=review["instrument_public_id"],
            responding_delegate_public_id=delegate_public_id,
            decision=decision.value,
            new_status=new_status.value,
            resolution_mode=resolution_mode.value,
            rationale=rationale,
            dispatch_version=int(atomic["dispatch_version"]),
            wall_clock=wall_clock,
        )
        return AiReviewDecisionResult(
            error_code=None,
            message="Decision recorded.",
            status=new_status,
            resolution_mode=resolution_mode,
            dispatch_version=int(atomic["dispatch_version"]),
            details={"previous_status": atomic["previous_status"]},
        )

