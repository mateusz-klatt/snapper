class ScopeGrantRow(TypedDict):
    """Row dict returned by scope grant queries.

    One row per ``wallet_operator_scope_grants`` SCD2 version. ``scope_kind``
    is exactly one of ``"underlying"`` / ``"instrument"``, and exactly one of
    ``underlying_public_id`` / ``instrument_public_id`` is non-NULL — enforced
    at the DB layer by the ``ck_scope_grants_scope_kind_xor`` CHECK constraint.
    """

    public_id: str
    operator_public_id: str
    wallet_public_id: str
    granted_by_user_public_id: str
    scope_kind: str
    underlying_public_id: str | None
    instrument_public_id: str | None
    note: str | None
    timestamp: datetime
    known_to: datetime
    session_id: str
    sequence_id: int


class WalletCredentialRow(TypedDict):
    """Row dict returned by wallet credential queries.

    One row per active ``wallet_credentials`` SCD2 version. The
    ``encrypted_payload`` is the Fernet-encrypted JSON envelope whose
    inner shape depends on ``credential_type`` (see ``WalletCredential``
    docstring). Decryption is the caller's responsibility — the
    repository never returns plaintext to keep accidental logging /
    serialization safe.
    """

    public_id: str
    wallet_public_id: str
    exchange: str
    credential_type: str
    encrypted_payload: str
    label: str | None
    timestamp: datetime
    session_id: str
    sequence_id: int


