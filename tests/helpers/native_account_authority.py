async def current_native_authority(
    scenario: NativeAuthorityScenario,
    result: SnapshotWriteResult,
    payload: NativeAccountAuthorityPayload,
    as_of: datetime | None = None,
) -> BoundNativeAccountAuthority:
    """Hold the real wallet fence while checking current native source and record knowledge.

    Args:
        scenario: Actual isolated repository, source clock and current trusted policy.
        result: Actual committed native record identity returned by the writer.
        payload: Exact native scope and route referenced by the caller.
        as_of: Explicit interpretation clock, defaulting to the controlled current fixture time.

    Returns:
        Verified current read identity without declaring financial permission or collateral.
    """
    async with scenario.repository.session() as session:
        await scenario.repository._begin_execution_insert_transaction(session)
        await scenario.repository._acquire_execution_fence_lock(
            session, payload.scope.wallet_public_id
        )
        return await require_current_native_account_authority(
            session,
            native_authority_reference(result, payload),
            scenario.policy,
            as_of if as_of is not None else scenario.clock.current,
        )


async def rotate_native_credential(scenario: NativeAuthorityScenario) -> None:
    """Persist a real SCD2 credential revision and bind a distinct actual SDK client.

    Args:
        scenario: Owned fixture whose original clients and sessions remain tracked for cleanup.
    """
    scenario.clock.current += timedelta(seconds=1)
    revision = scenario.clock.current
    async with scenario.repository.session() as session:
        previous = (
            await session.execute(
                select(WalletCredential).where(WalletCredential.known_to == KNOWN_TO_MAX)
            )
        ).scalar_one()
        previous.known_to = revision
        session.add(
            WalletCredential(
                public_id=native_authority_uuid(2),
                session_id=native_authority_uuid(9),
                sequence_id=20,
                timestamp=revision,
                wallet_public_id=native_authority_uuid(1),
                exchange="kraken_futures",
                credential_type="api_key_secret",
                encrypted_payload="rotated-fixture-never-decrypted",
            )
        )
        await session.commit()
    scenario.client, scenario.selection, sdk_session = _new_native_client(
        scenario.adapter, revision, "synthetic-key-rotated"
    )
    scenario.clients.append(scenario.client)
    scenario.sessions.append(sdk_session)
