@dataclass
class NativeAuthorityClock:
    """Control all real producer clocks without sleeps, source rewrites or a fake balance DTO."""

    current: datetime = NATIVE_AUTHORITY_TEST_TIME

    def now(self, zone: object) -> datetime:
        """Supply the same explicit UTC clock to actual HTTP and durable proof writers."""
        assert zone is UTC
        return self.current


class NativeAuthorityHttpAdapter(BaseAdapter):
    """Return original local HTTP bytes while observing actual committed attempts and key proofs."""

    def __init__(
        self,
        path: Path,
        clock: NativeAuthorityClock,
        observe_committed: Callable[[], tuple[int, int]] | None = None,
        observe_identity_proofs: Callable[[], tuple[tuple[str, str], ...]] | None = None,
    ) -> None:
        """Keep local source replies and independent committed-database probes inside this fixture.

        Args:
            path: Actual isolated SQLite file observed read-only by the HTTP worker.
            clock: Controlled local source clock without any real venue or monetary action.
            observe_committed: Independent observer of the same already initialized database.
            observe_identity_proofs: Independent complete proof rows from the same source database.
        """
        self.path = path
        self.clock = clock
        self.profiles = _PROFILES
        self.account_uid = native_authority_uuid(80)
        self.server_offset = timedelta(0)
        self.general_access: NativeKeyAccess = "READ_ONLY"
        self.fail_accounts = False
        self.block_accounts = False
        self.accounts_entered = threading.Event()
        self.accounts_release = threading.Event()
        self.calls: list[PreparedRequest] = []
        self.proofs_at_accounts_send: list[int] = []
        self.responses: list[Response] = []
        self._observe_committed = observe_committed or self._sqlite_committed_counts
        self._observe_identity_proofs = observe_identity_proofs

    def identity_proofs(self) -> tuple[tuple[str, str], ...]:
        """Read committed proof identities and canonical bytes at the actual physical SDK send.

        Returns:
            Actual same-database proof rows for exact identity and private-material exclusion checks.
        """
        if self._observe_identity_proofs is not None:
            return self._observe_identity_proofs()
        values: list[tuple[str, str]] = []
        with closing(sqlite3.connect(f"file:{self.path}?mode=ro", uri=True)) as connection:
            for public_id, payload in connection.execute(
                "SELECT public_id, canonical_payload FROM native_account_identity_proofs"
            ):
                assert isinstance(public_id, str) and isinstance(payload, str)
                values.append((public_id, payload))
        return tuple(values)

    def _sqlite_committed_counts(self) -> tuple[int, int]:
        """Read committed source facts independently of the producer's actual transaction.

        Returns:
            Actual retained attempt and identity-proof counts from the original SQLite source.
        """
        with closing(sqlite3.connect(f"file:{self.path}?mode=ro", uri=True)) as connection:
            attempts = connection.execute(
                "SELECT COUNT(*) FROM native_account_read_attempts"
            ).fetchone()
            proofs = connection.execute(
                "SELECT COUNT(*) FROM native_account_identity_proofs"
            ).fetchone()
        return int(attempts[0]), int(proofs[0])

    def send(self, request: PreparedRequest, *args: object, **kwargs: object) -> Response:
        """Exercise the pinned SDK's real signed Session using a socket-free response adapter.

        Args:
            request: Actual prepared request containing synthetic signing material only.
            args: Requests transport adapter positional arguments.
            kwargs: Actual routed stream, timeout and proxy arguments.

        Returns:
            Original streaming HTTP response for the exact requested identity/accounts endpoint.
        """
        self.calls.append(request)
        key_check = (request.url or "").endswith(_KEY_PATH)
        attempts, proofs = self._observe_committed()
        assert attempts >= 1
        if key_check:
            body = json.dumps(
                {
                    "apiKey": request.headers["APIKey"],
                    "accountUid": self.account_uid,
                    "permissions": {"general": self.general_access, "transfer": "NO_ACCESS"},
                    "iiban": NATIVE_AUTHORITY_PRIVATE_MARKER,
                }
            ).encode()
        elif (request.url or "").endswith(
            ("/derivatives/api/v3/openorders", "/derivatives/api/v3/openpositions")
        ):
            field = "openOrders" if (request.url or "").endswith("openorders") else "openPositions"
            body = json.dumps(
                {
                    "result": "success",
                    "serverTime": self.clock.current.isoformat().replace("+00:00", "Z"),
                    field: [],
                }
            ).encode()
        else:
            self.proofs_at_accounts_send.append(proofs)
            assert proofs >= 1
            if self.block_accounts:
                self.accounts_entered.set()
                if not self.accounts_release.wait(4):
                    raise TimeoutError("Local accounts response release was not delivered")
            if self.fail_accounts:
                raise RequestsConnectionError("Isolated accounts transport refused")
            server_time = (
                (self.clock.current + self.server_offset).isoformat().replace("+00:00", "Z")
            )
            body = (
                b'{"result":"success","serverTime":'
                + json.dumps(server_time).encode()
                + b',"accounts":'
                + self.profiles
                + b"}"
            )
        response = Response()
        response.status_code = 200
        response.url = request.url or ""
        response.request = request
        response.raw = HTTPResponse(body=BytesIO(body), status=200, preload_content=False)
        self.responses.append(response)
        return response

    def close(self) -> None:
        """Own no network socket or background transport resource."""


